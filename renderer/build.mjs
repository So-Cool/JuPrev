// Builds the renderer into NotebookKit's resources:
//   render.js — IIFE exposing globalThis.NBRender, for JavaScriptCore
//   style.css — KaTeX (fonts inlined as woff2 data URIs), highlight.js themes, notebook theme
// and the licence notices for every npm package that ends up in them:
//   ACKNOWLEDGEMENTS.md (repository root) and App/Credits.html (the About window)
import { build } from "esbuild";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "../Sources/NotebookKit/Resources");
const modules = join(here, "node_modules");

const { metafile } = await build({
  entryPoints: [join(here, "src/index.js")],
  bundle: true,
  minify: true,
  format: "iife",
  globalName: "NBRender",
  target: "safari17",
  legalComments: "eof",
  metafile: true,
  outfile: join(outDir, "render.js"),
});

const katexDir = join(modules, "katex/dist");
const katexCSS = readFileSync(join(katexDir, "katex.min.css"), "utf8")
  // Each @font-face lists woff2, woff and ttf; keep only an inlined woff2.
  .replace(/src:([^;}]+)/g, (_, sources) => {
    const woff2 = /url\((fonts\/[^)]+\.woff2)\)/.exec(sources);
    const data = readFileSync(join(katexDir, woff2[1])).toString("base64");
    return `src:url(data:font/woff2;base64,${data}) format("woff2")`;
  });

const hljsStyle = (name) => readFileSync(join(modules, `highlight.js/styles/${name}.min.css`), "utf8");

const css = [
  `/* Generated by renderer/build.mjs — do not edit. */`,
  katexCSS,
  hljsStyle("github"),
  `@media (prefers-color-scheme: dark){${hljsStyle("github-dark")}}`,
  readFileSync(join(here, "styles/notebook.css"), "utf8"),
].join("\n");

writeFileSync(join(outDir, "style.css"), css);
console.log(`render.js and style.css (${(css.length / 1024).toFixed(0)} KB) written to ${outDir}`);

// Licence notices for the bundled packages (katex is also in style.css, with its fonts).
// Credits.html is read by AppKit's HTML importer: it needs the charset declared and drops
// margins after <pre>, hence the explicit <br> before each package.
const bundled = new Set(["katex", "highlight.js"]);
for (const input of Object.keys(metafile.inputs)) {
  const match = /node_modules\/((?:@[^/]+\/)?[^/]+)/.exec(input);
  if (match) bundled.add(match[1]);
}
const notices = [...bundled].sort().map((name) => {
  const dir = join(modules, name);
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const licenceFile = readdirSync(dir).find((f) => /^(licen[sc]e|copying)/i.test(f));
  if (!licenceFile) throw new Error(`${name} has no licence file`);
  return { name, version: pkg.version, licence: pkg.license, text: readFileSync(join(dir, licenceFile), "utf8").trim() };
});

const root = join(here, "..");
writeFileSync(
  join(root, "ACKNOWLEDGEMENTS.md"),
  [
    "# Acknowledgements",
    "",
    "<!-- Generated by renderer/build.mjs — do not edit. -->",
    "",
    "JuPrev bundles the following packages in its notebook renderer.",
    ...notices.flatMap((n) => ["", `## ${n.name} ${n.version} (${n.licence})`, "", "```", n.text, "```"]),
    "",
  ].join("\n"),
);

const escape = (t) => t.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
writeFileSync(
  join(root, "App/Credits.html"),
  `<!-- Generated by renderer/build.mjs — do not edit. -->
<html><head><meta charset="utf-8"></head><body style="font: 11px -apple-system, sans-serif">
<p>A minimal viewer and Quick Look previews for Jupyter notebooks.<br>
<a href="https://github.com/So-Cool/JuPrev">github.com/So-Cool/JuPrev</a> · MIT License</p>
<p><b>Includes</b></p>
${notices.map((n) => `<br>\n<p><b>${n.name} ${n.version}</b> (${n.licence})</p>\n<pre style="font: 9px ui-monospace, Menlo, monospace; white-space: pre-wrap">${escape(n.text)}</pre>`).join("\n")}
</body></html>
`,
);
console.log(`Notices for ${notices.length} packages written to ACKNOWLEDGEMENTS.md and App/Credits.html`);
