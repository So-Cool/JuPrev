// Builds the renderer into NotebookKit's resources:
//   render.js — IIFE exposing globalThis.NBRender, for JavaScriptCore
//   style.css — KaTeX (fonts inlined as woff2 data URIs), highlight.js themes, notebook theme
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "../Sources/NotebookKit/Resources");
const modules = join(here, "node_modules");

await build({
  entryPoints: [join(here, "src/index.js")],
  bundle: true,
  minify: true,
  format: "iife",
  globalName: "NBRender",
  target: "safari17",
  legalComments: "eof",
  outfile: join(outDir, "render.js"),
});

const katexDir = join(modules, "katex/dist");
const katexCSS = readFileSync(join(katexDir, "katex.min.css"), "utf8")
  // Each @font-face lists woff2, woff and ttf; keep only an inlined woff2.
  .replace(/src:([^;}]+)/g, (_, sources) => {
    const woff2 = /url\((fonts\/[^)]+\.woff2)\)/.exec(sources);
    const data = readFileSync(join(katexDir, woff2[1])).toString("base64");
    return `src:url(data:font/woff2;base64,${data}) format("woff2")`;
  });

const hljsStyle = (name) => readFileSync(join(modules, `highlight.js/styles/${name}.min.css`), "utf8");

const css = [
  `/* Generated by renderer/build.mjs — do not edit. */`,
  katexCSS,
  hljsStyle("github"),
  `@media (prefers-color-scheme: dark){${hljsStyle("github-dark")}}`,
  readFileSync(join(here, "styles/notebook.css"), "utf8"),
].join("\n");

writeFileSync(join(outDir, "style.css"), css);
console.log(`render.js and style.css (${(css.length / 1024).toFixed(0)} KB) written to ${outDir}`);
